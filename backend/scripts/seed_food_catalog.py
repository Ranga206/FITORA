def generate_deterministic_uuid(source_code: str) -> uuid.UUID:
    """Generate a stable deterministic UUID from source identifier."""
    return uuid.uuid5(uuid.NAMESPACE_DNS, f"fitora.usda.fdc.{source_code}")


def build_seed_records() -> list[dict[str, Any]]:
    """Build and validate seed records ensuring compliance with Decisions 4, 6 & 7."""
    records: list[dict[str, Any]] = []

    for item in SEED_FOODS_DATA:
        # Strict validation before seeding
        validate_food_conditional_rules(
            nutrition_reference_basis=item["nutrition_reference_basis"],
            serving_size=item["serving_size"],
            serving_unit=item["serving_unit"],
            serving_weight_g=item["serving_weight_g"],
            serving_volume_ml=item["serving_volume_ml"],
            calories=item["calories"],
            protein=item["protein"],
            carbohydrates=item["carbohydrates"],
            fat=item["fat"],
            data_review_status="verified",
            source_name="USDA FoodData Central",
        )

        food_id = generate_deterministic_uuid(item["source_code"])
        records.append(
            {
                "id": food_id,
                "name": item["name"],
                "category": item["category"],
                "preparation_state": item["preparation_state"],
                "food_type": item["food_type"],
                "nutrition_reference_basis": item["nutrition_reference_basis"],
                "serving_size": item["serving_size"],
                "serving_unit": item["serving_unit"],
                "serving_weight_g": item["serving_weight_g"],
                "serving_volume_ml": item["serving_volume_ml"],
                "calories": item["calories"],
                "protein": item["protein"],
                "carbohydrates": item["carbohydrates"],
                "fat": item["fat"],
                "source_name": "USDA FoodData Central",
                "source_code": item["source_code"],
                "source_data_type": item["source_data_type"],
                "source_release_version": item.get(
                    "source_release_version", "SR Legacy (April 2018)"
                ),
                "data_review_status": "verified",
                "is_system": True,
            }
        )

    return records


def seed_food_catalog(target_engine=None) -> int:
    """Seed the food items into the database with total idempotency and overwrite protection."""
    eng = target_engine or engine
    records = build_seed_records()

    with eng.begin() as connection:
        seed_ids = [record["id"] for record in records]

        # 1. Clean up obsolete system-seeded records that are no longer part of active seed data
        connection.execute(
            delete(FoodItem).where(
                FoodItem.is_system == True,
                FoodItem.id.not_in(seed_ids),
            )
        )

        # 2. Upsert seed records with overwrite protection: only update records where is_system is True
        for record in records:
            stmt = (
                insert(FoodItem)
                .values(**record)
                .on_conflict_do_update(
                    index_elements=["id"],
                    set_={
                        "name": record["name"],
                        "category": record["category"],
                        "preparation_state": record["preparation_state"],
                        "food_type": record["food_type"],
                        "nutrition_reference_basis": record[
                            "nutrition_reference_basis"
                        ],
                        "serving_size": record["serving_size"],
                        "serving_unit": record["serving_unit"],
                        "serving_weight_g": record["serving_weight_g"],
                        "serving_volume_ml": record["serving_volume_ml"],
                        "calories": record["calories"],
                        "protein": record["protein"],
                        "carbohydrates": record["carbohydrates"],
                        "fat": record["fat"],
                        "source_name": record["source_name"],
                        "source_code": record["source_code"],
                        "source_data_type": record["source_data_type"],
                        "source_release_version": record["source_release_version"],
                        "data_review_status": record["data_review_status"],
                        "is_system": record["is_system"],
                    },
                    where=(FoodItem.is_system == True),
                )
            )
            connection.execute(stmt)

    return len(records)


def main() -> None:
    settings = get_settings()
    if settings.environment != "development":
        raise RuntimeError("Food catalog seeding is allowed only in development.")

    count = seed_food_catalog()
    print(f"Successfully seeded {count} verified USDA FoodData Central items.")


if __name__ == "__main__":
    main()
